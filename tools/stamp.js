#!/usr/bin/env node
if (typeof require === 'function' && typeof module !== 'undefined' && require.main === module) require('./exit_log.js').watch('tools/stamp.js'); // failed runs -> test.js report
/**
 * Build stamp for fc2/ (no build step needed, just run it): `node tools/stamp.js` (test/fc2_pages_test.js runs it for you).
 * 1. Hashes every file fc2/index.html loads (plus index.html itself, ignoring the ?v= values).
 * 2. Rewrites every local <script src> / stylesheet href in index.html to `?v=<hash>`, so a phone that cached an old index.html still
 *    loads one consistent set of files, and a new push is never mixed with stale scripts.
 * 3. Writes fc2/version.js (window.FC2Version = { hash, built }), shown at the bottom of the Menu and in the error panel.
 * `built` only changes when the hash does, so running it repeatedly never dirties the tree. `--check` changes nothing: exit 1 if stale.
 */
'use strict';
require('./cli_help.js').exitWithHeaderHelp(__filename);

const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const DIR = path.resolve(__dirname, '..', 'fc2');
const PAGE = path.join(DIR, 'index.html');
const VERSION = path.join(DIR, 'version.js');
const TAG = /(<script[^>]*\ssrc="|<link[^>]*\shref=")([^"?]+)(\?v=[^"]*)?"/g;
const local = ref => !/^(https?:)?\/\//.test(ref) && !ref.startsWith('data:');

function stamp(write) {
	const html = fs.readFileSync(PAGE, 'utf8');
	const assets = [...html.matchAll(TAG)].map(m => m[2]).filter(local).filter(ref => path.basename(ref) !== 'version.js');
	const h = crypto.createHash('sha1');
	h.update(html.replace(TAG, (m, a, ref) => `${a}${ref}"`));
	for (const ref of [...new Set(assets)].sort()) {
		const f = path.resolve(DIR, ref);
		if (fs.existsSync(f)) { h.update(ref); h.update(fs.readFileSync(f)); }
	}
	const hash = h.digest('hex').slice(0, 8);
	const old = fs.existsSync(VERSION) ? fs.readFileSync(VERSION, 'utf8') : '';
	const oldHash = (old.match(/hash: '([0-9a-f]+)'/) || [])[1], oldBuilt = (old.match(/built: '([^']+)'/) || [])[1];
	const built = oldHash === hash && oldBuilt ? oldBuilt : new Date().toISOString();
	const nextHtml = html.replace(TAG, (m, a, ref) => (local(ref) ? `${a}${ref}?v=${hash}"` : m));
	const nextVersion = `// Generated by tools/stamp.js: do not edit by hand.\nwindow.FC2Version = { hash: '${hash}', built: '${built}' };\n`;
	const stale = nextHtml !== html || nextVersion !== old;
	if (write && stale) { fs.writeFileSync(PAGE, nextHtml); fs.writeFileSync(VERSION, nextVersion); }
	return { hash, built, stale };
}

if (require.main === module) {
	const check = process.argv.includes('--check'), r = stamp(!check);
	console.log(`${check ? (r.stale ? 'STALE' : 'current') : (r.stale ? 'stamped' : 'unchanged')}: ${r.hash} (built ${r.built})`);
	process.exit(check && r.stale ? 1 : 0);
}
module.exports = { stamp };
